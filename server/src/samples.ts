type Sample = { text: string; choices: [string, string, string, string]; correctIndex: number };

/** 正解と誤答3つから問題を作る。正解の位置は position。 */
function q(position: 0 | 1 | 2 | 3, text: string, correct: string, w1: string, w2: string, w3: string): Sample {
  const choices = [w1, w2, w3];
  choices.splice(position, 0, correct);
  return { text, choices: choices as [string, string, string, string], correctIndex: position };
}

